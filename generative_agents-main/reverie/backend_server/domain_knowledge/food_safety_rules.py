def retrieve_food_safety_rules(query: str, top_k: int = 3) -> List[Dict[str, str]]:
  """按简单关键词匹配返回最多 top_k 条规则。

  当前实现：
  - query 与规则文本/建议都转为小写
  - 用子串匹配统计命中 token 数
  - 得分为 0 的规则会被忽略；若全部为 0，则按原顺序取前 top_k 条
  """
  query = (query or "").strip()
  if not query:
    return RULES[:top_k]

  q_tokens = [t for t in query.lower().replace("\n", " ").split(" ") if t]
  if not q_tokens:
    return RULES[:top_k]

  scored = []
  for rule in RULES:
    blob = f"{rule['text']} {rule['guidance']}".lower()
    score = sum(1 for t in q_tokens if t in blob)
    if score > 0:
      scored.append((score, rule))

  if not scored:
    return RULES[:top_k]

  scored.sort(key=lambda x: x[0], reverse=True)
  return [r for _, r in scored[:top_k]]


def format_rules_for_prompt(rules: List[Dict[str, str]]) -> str:
  """将若干条规则格式化为多行文本，便于塞进 LLM prompt。"""
  lines: List[str] = []
  for r in rules:
    line = f"[{r['id']}]({r['category']},{r['polarity']}): {r['text']} 建议：{r['guidance']}"
    lines.append(line)
  return "\n".join(lines) if lines else "(当前规则库未返回匹配项)"
